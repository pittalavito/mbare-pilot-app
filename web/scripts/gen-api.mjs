// The API's OpenAPI schema -> src/api/schema.d.ts: the types of every endpoint.
// Python exports the schema without starting the API (no DB, no Redis needed),
// so the types follow the backend's code, not a running server.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import openapiTS, { astToString } from "openapi-typescript";

const root = resolve("..");
const python = resolve(root, process.platform === "win32" ? ".venv/Scripts/python.exe" : ".venv/bin/python");
const code = "import json, sys; sys.path.insert(0, 'src'); from core.app import create_app; print(json.dumps(create_app().openapi()))";
const schema = execFileSync(python, ["-c", code], { cwd: root, encoding: "utf-8", env: { ...process.env, PYTHONIOENCODING: "utf-8" } });

const ast = await openapiTS(JSON.parse(schema));
writeFileSync("src/api/schema.d.ts", `// Generated by "npm run gen:api" from the API's OpenAPI schema: do not edit.\n${astToString(ast)}`);
console.log("src/api/schema.d.ts updated");
